use std::{env, fs, path::PathBuf};

fn main() {
    let icons = write_build_icons();
    let icon_path_value = json_string(&icons.context_png.to_string_lossy());
    let tauri_config = format!(r#"{{"bundle":{{"icon":[{icon_path_value}]}}}}"#);

    env::set_var("TAURI_CONFIG", &tauri_config);
    println!("cargo:rustc-env=TAURI_CONFIG={tauri_config}");

    let windows = tauri_build::WindowsAttributes::new().window_icon_path(icons.windows_ico);
    let attributes = tauri_build::Attributes::new().windows_attributes(windows);
    tauri_build::try_build(attributes).expect("运行 Tauri build script 失败");
}

struct BuildIcons {
    context_png: PathBuf,
    windows_ico: PathBuf,
}

fn write_build_icons() -> BuildIcons {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("缺少 OUT_DIR"));
    let context_png = out_dir.join("codex-atlas-context.png");
    let windows_ico = out_dir.join("codex-atlas-build.ico");

    // 仅为 Tauri 编译写入 Cargo 输出目录，避免在源码树中保留图标产物。
    fs::write(&context_png, CONTEXT_PNG).expect("写入临时 Tauri PNG 图标失败");
    fs::write(&windows_ico, WINDOWS_RESOURCE_ICO).expect("写入临时 Tauri ICO 图标失败");

    BuildIcons {
        context_png,
        windows_ico,
    }
}

fn json_string(value: &str) -> String {
    let mut escaped = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => escaped.push_str("\\\""),
            '\\' => escaped.push_str("\\\\"),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            _ => escaped.push(ch),
        }
    }
    escaped.push('"');
    escaped
}

